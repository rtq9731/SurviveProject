namespace Survive.World
{
    /// <summary>
    /// 지상이 갈린 구역들.
    ///
    /// <b>갈라 놓은 것은 지면이 아니라 액체다</b>(기획서 §2.1). 뭍은 한 덩어리이고
    /// (세계관 §2 — 무대는 지상 한 덩어리 + 호수 + 착륙선), 그 한 덩어리를 가르는 것은
    /// 파고든 액면이다. 그래서 이 열거형에는 「땅 조각」이 아니라 <b>액체가 만든 구역</b>이
    /// 들어간다 - 값의 순서가 곧 걸어 나가는 순서다.
    ///
    /// <b>이름은 자리가 아니라 성격이다.</b> 지상 지형은 아직 없고(스펙 §13) 나중에
    /// 통째로 만들어진다. 자리 이름(「첫째 땅」·「저 섬」)을 붙여 두면 지형이 서는 날
    /// 이름부터 다시 갈아야 하지만, <b>성격 이름</b>이면 볼륨만 갖다 놓으면 된다 -
    /// 수로는 어디를 파고들든 수로이고, 여울은 어디가 얕든 여울이다.
    ///
    /// <b>액체 세 얼굴이 이름에서 읽힌다.</b> 이것이 이 구역 체계의 존재 이유다.
    /// <see cref="Inlet"/>은 파고들어 좁고 깊고, <see cref="Shallows"/>는 바닥이
    /// 받쳐 주고, <see cref="OpenWater"/>는 넓고 깊다. 셋의 위험도가
    /// <b>단조 증가가 아닌 것</b>이 요점이다 - <see cref="SurfaceZones.Order"/>를 보라.
    ///
    /// <b>이름은 여기 적지 않는다.</b> 화면에 나갈 글자는 번역 표가 가진다
    /// (<see cref="SurfaceZones.NameKey"/>).
    /// </summary>
    public enum SurfaceZone
    {
        /// <summary>착륙선이 선 자리. 첫 거점이고 걸어 나가는 출발점이다(기획서 §5.16).</summary>
        Landing,

        /// <summary>
        /// 호수. <b>증발과 강수로 내려 고인 진짜 물</b>이라 마실 수 있고 담가도 무해하다
        /// (세계관 §2). 지상에서 생물이 사는 자리가 여기뿐이다.
        ///
        /// <b>무해한 이유가 다른 두 액체 중 하나다.</b> 여울은 발이 바닥에 닿아서 무해하고
        /// 호수는 <b>물이라서</b> 무해하다 - 깊어도 넓어도 값이 0이다. 그래서 이 둘이
        /// 나란히 있어야 플레이어가 「깊이만 보면 안 된다」까지 배운다.
        /// </summary>
        Lake,

        /// <summary>
        /// 액면이 뭍을 파고든 자리. <b>좁지만 깊다</b> - 헤엄쳐 건너면 살이 깎인다.
        /// 기획서 §2.1이 둥지로 가는 길을 「액면이 육지를 파고든 수로」라 부르는 그것이다.
        /// </summary>
        Inlet,

        /// <summary>액면에서 먼 안쪽 뭍. 물가에서 물러선 자리라 상시로는 낫이 오지 않는다(§4.5).</summary>
        Inland,

        /// <summary>
        /// 발이 바닥에 닿는 액면. <b>그냥 걸어서 건넌다 - 무해하다.</b>
        /// 무해의 근거가 「좁아서」가 아니라 「딛고 있어서」라, 열 배로 넓혀도 답이 같다.
        /// </summary>
        Shallows,

        /// <summary>먼바다 앞 마지막 뭍. 낫이 상시로 나오는 끝이 여기다(§4.5 서식 범위).</summary>
        Shore,

        /// <summary>
        /// 넓고 깊은 액면. <b>헤엄쳐서는 못 건넌다</b> - 액면 보행 장비가 여는 것이 이것이다.
        /// </summary>
        OpenWater,

        /// <summary>먼바다 너머. 걸어서 닿는 것이 아니라 <b>값을 치르고</b> 닿는 자리다.</summary>
        Farside,
    }
}

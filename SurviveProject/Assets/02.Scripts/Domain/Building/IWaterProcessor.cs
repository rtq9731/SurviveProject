namespace Survive.Building
{
    /// <summary>
    /// 착륙선의 <b>처리장치</b>. 매크로늄에서 물만 분리한다 —
    /// 무한하지만 느리다(기획서 §5.15의 수분 확보 수단 셋 중 하나).
    ///
    /// <b>여기에는 값이 하나도 없다.</b> 속도도 통 크기도 이 파일이 정하지 않는다 —
    /// 수분·식량 축을 세우는 쪽이 정한다. 그쪽이 아직 서지 않았으므로 지금은
    /// <see cref="Configured"/>가 거짓이고, 그동안 <see cref="Pooled"/>는 자라지 않는다.
    ///
    /// <b>왜 0을 적어 두지 않는가.</b> 「초당 0」과 「아직 아무도 안 정했다」는 다른 말이다.
    /// 0을 값으로 박아 두면 다음 사람이 그것을 <b>정해진 값</b>으로 읽고, 물이 안 나오는
    /// 이유를 처리장치가 고장 난 데서 찾는다. 게이트도 마찬가지다 — 0을 재는 검사는
    /// 값이 안 들어와도 초록이다.
    ///
    /// <b>왜 무한인가.</b> 원료가 매크로늄이고 그것은 지평선 너머까지 있다(세계관 §3).
    /// 이 장치가 거는 압박은 재고가 아니라 <b>느리다는 것</b>이고, 그래서 멀리 나가는
    /// 사람은 이것만 믿을 수 없다. 「관리 대상이 게이지가 아니라 거리」라는 §5.15의
    /// 선을 지키는 것이 이 성질이다.
    /// </summary>
    public interface IWaterProcessor
    {
        /// <summary>속도와 통 크기가 들어왔는가. 거짓이면 아무것도 모이지 않는다.</summary>
        bool Configured { get; }

        /// <summary>초당 나오는 양. 단위는 수분 축이 정한다.</summary>
        float UnitsPerSecond { get; }

        /// <summary>통 크기. 여기까지 차면 멈춘다 — 무한한 것은 원료이지 통이 아니다.</summary>
        float Capacity { get; }

        /// <summary>지금 통에 모여 있는 양.</summary>
        float Pooled { get; }

        /// <summary>통에서 이만큼 받아 간다. 돌려주는 것은 <b>실제로 받아 간 양</b>이다.</summary>
        float Draw(float units);
    }
}

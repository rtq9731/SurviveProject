namespace Survive.Items
{
    /// <summary>
    /// 장비 슬롯의 종류. 아이템 하나가 어느 자리에 걸리는지를 정한다.
    ///
    /// <b>왜 종류를 나누는가.</b> 슬롯이 하나뿐이면 열거형이 필요 없다. 그러나
    /// 이 자리에 들어올 후보(스펙 §8-1 매크로늄 방호복 등)가 이미 예고돼 있고,
    /// 그때 "랜턴을 빼야 방호복을 입는다"가 되면 지금 없앤 경쟁이 도로 살아난다.
    /// 종류마다 자리가 하나씩이면 늘어나도 서로 밀어내지 않는다.
    ///
    /// <b>지금 값이 하나뿐인 것은 의도다.</b> 확실한 것만 넣는다
    /// (판단 근거는 <see cref="EquipmentSlots"/> 주석 참조).
    /// </summary>
    public enum EquipmentSlotKind
    {
        /// <summary>장비가 아니다. 보통의 소지품 칸으로 간다.</summary>
        None = 0,

        /// <summary>조명. 랜턴이 여기 걸린다.</summary>
        Light = 1,
    }
}
